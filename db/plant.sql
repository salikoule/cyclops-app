-- Plant records. Ordinary tables and real foreign keys.
-- Sign-in stays in Anvil's users table. This file does not create it.

CREATE SCHEMA plant;

CREATE TABLE plant.item_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    item_type text NOT NULL DEFAULT '',
    role text NOT NULL DEFAULT ''
);

CREATE TABLE plant.machine_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT ''
);

CREATE TABLE plant.units (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT ''
);

CREATE TABLE plant.variant_attributes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT ''
);

CREATE TABLE plant.person_roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    runs_machines boolean NOT NULL DEFAULT false,
    status text NOT NULL DEFAULT ''
);

CREATE TABLE plant.shifts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    start_time text NOT NULL DEFAULT '',
    end_time text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT ''
);

CREATE TABLE plant.stoppage_causes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    category text NOT NULL DEFAULT '',
    planned boolean NOT NULL DEFAULT false,
    changeover boolean NOT NULL DEFAULT false,
    status text NOT NULL DEFAULT ''
);

CREATE TABLE plant.scrap_reasons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    category text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT ''
);

CREATE TABLE plant.machines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    alias text NOT NULL DEFAULT '',
    machine_type_id bigint REFERENCES plant.machine_types (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    attached_to_id bigint REFERENCES plant.machines (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    floor_number double precision,
    serial text NOT NULL DEFAULT '',
    euromap text NOT NULL DEFAULT '',
    year text NOT NULL DEFAULT '',
    changeover_min double precision,
    location text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT '',
    notes text NOT NULL DEFAULT ''
);

CREATE TABLE plant.personnel (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    role_id bigint REFERENCES plant.person_roles (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    status text NOT NULL DEFAULT ''
);

CREATE TABLE plant.items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    item_type text NOT NULL DEFAULT '',
    category_id bigint REFERENCES plant.item_categories (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    unit_id bigint REFERENCES plant.units (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    erp_code text NOT NULL DEFAULT '',
    supplier text NOT NULL DEFAULT '',
    properties jsonb,
    status text NOT NULL DEFAULT '',
    notes text NOT NULL DEFAULT '',
    parent_id bigint REFERENCES plant.items (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE plant.molds (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    cavities double precision,
    shot_weight_g double precision,
    location text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT '',
    notes text NOT NULL DEFAULT ''
);

CREATE TABLE plant.recipes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    item_id bigint REFERENCES plant.items (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    mold_id bigint REFERENCES plant.molds (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    machine_id bigint REFERENCES plant.machines (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    status text NOT NULL DEFAULT '',
    standard boolean NOT NULL DEFAULT false,
    cycle_s double precision,
    temps jsonb,
    injection jsonb,
    extra jsonb,
    settings_note text NOT NULL DEFAULT '',
    comment text NOT NULL DEFAULT ''
);

CREATE TABLE plant.production_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    item_id bigint REFERENCES plant.items (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    quantity double precision,
    due_date date,
    status text NOT NULL DEFAULT '',
    erp_order_no text NOT NULL DEFAULT '',
    notes text NOT NULL DEFAULT ''
);

CREATE TABLE plant.production_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    order_id bigint REFERENCES plant.production_orders (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    recipe_id bigint REFERENCES plant.recipes (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    shift_id bigint REFERENCES plant.shifts (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    operator_id bigint REFERENCES plant.personnel (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    started_at timestamptz,
    ended_at timestamptz,
    good_qty double precision,
    cavities_running double precision,
    cycle_s double precision,
    status text NOT NULL DEFAULT '',
    notes text NOT NULL DEFAULT ''
);

CREATE TABLE plant.lots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    number text NOT NULL DEFAULT '',
    item_id bigint REFERENCES plant.items (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    origin text NOT NULL DEFAULT '',
    run_id bigint REFERENCES plant.production_runs (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    supplier_lot text NOT NULL DEFAULT '',
    received_at timestamptz,
    quantity double precision,
    status text NOT NULL DEFAULT '',
    notes text NOT NULL DEFAULT ''
);

CREATE TABLE plant.stoppages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    machine_id bigint REFERENCES plant.machines (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    run_id bigint REFERENCES plant.production_runs (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    started_at timestamptz,
    ended_at timestamptz,
    cause_id bigint REFERENCES plant.stoppage_causes (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    description text NOT NULL DEFAULT '',
    fix text NOT NULL DEFAULT '',
    reported_by_id bigint REFERENCES plant.personnel (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE plant.changeovers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    machine_id bigint REFERENCES plant.machines (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    from_run_id bigint REFERENCES plant.production_runs (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    to_run_id bigint REFERENCES plant.production_runs (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    from_item_id bigint REFERENCES plant.items (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    to_item_id bigint REFERENCES plant.items (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    kind text NOT NULL DEFAULT '',
    started_at timestamptz,
    ended_at timestamptz,
    lost_h double precision,
    source text NOT NULL DEFAULT '',
    confidence text NOT NULL DEFAULT '',
    stoppage_id bigint REFERENCES plant.stoppages (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    basis text NOT NULL DEFAULT '',
    notes text NOT NULL DEFAULT ''
);

CREATE TABLE plant.recipe_inputs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id bigint NOT NULL REFERENCES plant.recipes (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    item_id bigint REFERENCES plant.items (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    share_pct double precision
);

CREATE TABLE plant.run_scrap (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES plant.production_runs (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    reason_id bigint REFERENCES plant.scrap_reasons (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    quantity double precision
);

CREATE TABLE plant.run_inputs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES plant.production_runs (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    lot_id bigint REFERENCES plant.lots (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    quantity double precision
);

CREATE TABLE plant.item_attributes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL REFERENCES plant.items (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    attribute_id bigint REFERENCES plant.variant_attributes (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    value text NOT NULL DEFAULT ''
);

CREATE TABLE plant.item_machines (
    item_id bigint NOT NULL REFERENCES plant.items (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    machine_id bigint NOT NULL REFERENCES plant.machines (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    position integer NOT NULL,
    PRIMARY KEY (item_id, position)
);

CREATE TABLE plant.personnel_machines (
    personnel_id bigint NOT NULL REFERENCES plant.personnel (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    machine_id bigint NOT NULL REFERENCES plant.machines (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    position integer NOT NULL,
    PRIMARY KEY (personnel_id, position)
);

CREATE TABLE plant.access_grants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    role text NOT NULL DEFAULT '',
    screens jsonb,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE plant.audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at timestamptz NOT NULL,
    email text NOT NULL DEFAULT '',
    record_table text NOT NULL DEFAULT '',
    record text NOT NULL DEFAULT '',
    action text NOT NULL DEFAULT '',
    summary text NOT NULL DEFAULT '',
    changes jsonb
);

CREATE TABLE plant.notification_prefs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    maintenance boolean NOT NULL DEFAULT false,
    breakdowns boolean NOT NULL DEFAULT false
);

CREATE TABLE plant.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL DEFAULT '',
    kind text NOT NULL DEFAULT '',
    record text NOT NULL DEFAULT '',
    title text NOT NULL DEFAULT '',
    body text NOT NULL DEFAULT '',
    created_at timestamptz,
    read_at timestamptz
);

CREATE UNIQUE INDEX access_grants_email_key ON plant.access_grants (lower(btrim(email)));
CREATE UNIQUE INDEX notification_prefs_email_key ON plant.notification_prefs (lower(btrim(email)));
CREATE INDEX audit_events_record_idx ON plant.audit_events (record_table, record, at DESC);
CREATE INDEX notifications_email_idx ON plant.notifications (lower(btrim(email)), created_at DESC);

CREATE INDEX machines_type_idx ON plant.machines (machine_type_id);
CREATE INDEX machines_attached_idx ON plant.machines (attached_to_id);
CREATE INDEX personnel_role_idx ON plant.personnel (role_id);
CREATE INDEX items_category_idx ON plant.items (category_id);
CREATE INDEX items_unit_idx ON plant.items (unit_id);
CREATE INDEX items_parent_idx ON plant.items (parent_id);
CREATE INDEX recipes_item_idx ON plant.recipes (item_id);
CREATE INDEX recipes_mold_idx ON plant.recipes (mold_id);
CREATE INDEX recipes_machine_idx ON plant.recipes (machine_id);
CREATE INDEX orders_item_idx ON plant.production_orders (item_id);
CREATE INDEX runs_order_idx ON plant.production_runs (order_id);
CREATE INDEX runs_recipe_idx ON plant.production_runs (recipe_id);
CREATE INDEX runs_shift_idx ON plant.production_runs (shift_id);
CREATE INDEX runs_operator_idx ON plant.production_runs (operator_id);
CREATE INDEX runs_started_idx ON plant.production_runs (started_at);
CREATE INDEX lots_item_idx ON plant.lots (item_id);
CREATE INDEX lots_run_idx ON plant.lots (run_id);
CREATE INDEX stoppages_machine_idx ON plant.stoppages (machine_id);
CREATE INDEX stoppages_run_idx ON plant.stoppages (run_id);
CREATE INDEX stoppages_cause_idx ON plant.stoppages (cause_id);
CREATE INDEX stoppages_started_idx ON plant.stoppages (started_at);
CREATE INDEX changeovers_machine_idx ON plant.changeovers (machine_id);
CREATE INDEX changeovers_from_run_idx ON plant.changeovers (from_run_id);
CREATE INDEX changeovers_to_run_idx ON plant.changeovers (to_run_id);
CREATE INDEX changeovers_ended_idx ON plant.changeovers (ended_at);
CREATE INDEX recipe_inputs_recipe_idx ON plant.recipe_inputs (recipe_id);
CREATE INDEX recipe_inputs_item_idx ON plant.recipe_inputs (item_id);
CREATE INDEX run_scrap_run_idx ON plant.run_scrap (run_id);
CREATE INDEX run_inputs_run_idx ON plant.run_inputs (run_id);
CREATE INDEX run_inputs_lot_idx ON plant.run_inputs (lot_id);
CREATE INDEX item_attributes_item_idx ON plant.item_attributes (item_id);
CREATE INDEX item_machines_machine_idx ON plant.item_machines (machine_id);
CREATE INDEX personnel_machines_machine_idx ON plant.personnel_machines (machine_id);
